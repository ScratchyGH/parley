const{slash}=await import('../public/js/slash.js')
let pass=0,fail=0
const t=(a,b,n)=>{if(JSON.stringify(a)===JSON.stringify(b))pass++;else{fail++;console.log('FAIL',n,JSON.stringify(a),JSON.stringify(b))}}
t(slash('hello'),{text:'hello'},'plain text untouched')
t(slash('/shrug'),{text:'¯\\\\\\_(ツ)\\_/¯'},'shrug alone')
t(slash('/shrug oh well'),{text:'oh well ¯\\\\\\_(ツ)\\_/¯'},'shrug with text')
t(slash('/TABLEFLIP'),{text:'(╯°□°)╯︵ ┻━┻'},'case insensitive')
t(slash('/unflip calm'),{text:'calm ┬─┬ ノ( ゜-゜ノ)'},'unflip')
t(slash('/lenny'),{text:'( ͡° ͜ʖ ͡°)'},'lenny')
t(slash('/me waves'),{text:'*waves*'},'me')
t(slash('/me'),{error:'Write what you are doing after /me'},'me needs text')
t(slash('/spoiler the ending'),{text:'||the ending||'},'spoiler')
t(slash('/spoiler'),{error:'Write the text to hide after /spoiler'},'spoiler needs text')
t(slash('/gif cats'),{gif:'cats'},'gif with query')
t(slash('/gif'),{gif:''},'gif without query')
t(slash('/unknown thing'),{text:'/unknown thing'},'unknown commands are sent as typed')
t(slash('see /shrug'),{text:'see /shrug'},'commands only at the start')
t(slash('/path/to/file'),{text:'/path/to/file'},'paths are not commands')
t(slash('/shrug\nmore'),{text:'more ¯\\\\\\_(ツ)\\_/¯'},'shrug keeps following lines')
console.log(`${pass} passed, ${fail} failed`)
process.exit(fail?1:0)
